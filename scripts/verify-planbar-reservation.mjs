import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { buildPlanbarCustomer, buildEnterPlanbarCustomer, buildPrefixedPlanbarCustomer, isoWeekRange, mergePlanbarSchedulingProgress, planbarSchedulingKey, planbarSchedulingSummary } from '../operations/customer-scheduling.js';

const root = await mkdtemp(path.join(os.tmpdir(), 'iva-reservation-test-'));
process.env.DATA_DIR = path.join(root, 'data');
process.env.IVA_CODEX_TASK_ROOT = path.join(root, 'tasks');
const tasks = await import('../local-mac-helper/codex-tasks.mjs');
const operations = await import('../operations/store.js');
const projects = await import('../projects/store.js');
const { planbarSkill } = await import('../skills/planbar.js');
const input = { customerName: 'Fixture Kunde', partnerId: 'heat-hero', partnerPrefix: 'HH', partnerName: 'Heat Hero', isoYear: 2026, week: 39, materialDeliverySpace: true, theftWeatherProtected: false };
const reservation = { customerId: 'test-customer', appointmentId: 'test-appointment', resourceId: 'test-team', resourceName: 'Testteam', isoYear: 2026, week: 39, ...isoWeekRange(2026, 39), verified: true, identityVerified: true, verifiedAt: new Date().toISOString() };
assert.throws(() => isoWeekRange(2025, 53), /existiert/);
assert.equal(isoWeekRange(2026, 53).startDate, '2026-12-28');
for (const build of [buildPlanbarCustomer, buildEnterPlanbarCustomer, value => buildPrefixedPlanbarCustomer({prefix: 'DW', ...value})]) {
  const customer = build({ firstName: 'Fixture', lastName: 'Kunde' });
  assert.equal(customer.email, '');
  assert.equal(customer.phone, '');
  assert.equal(customer.address, '');
}
assert.throws(() => buildPlanbarCustomer({firstName: 'Fixture'}), /Nachname/);
assert.throws(() => mergePlanbarSchedulingProgress(null, {status: 'completed', reservation, missingDetails: [], remainingActions: [], completionVerified: true}), /Zuerst/);
assert.throws(() => mergePlanbarSchedulingProgress(null, {status: 'reserved'}), /nachweis/i);
for (const invalid of [{verified:false}, {identityVerified:false}, {appointmentId:''}, {resourceName:'Dawid Service'}, {resourceName:'Antonio Lausitsch'}, {endDateExclusive:'2026-09-25'}, {verifiedAt:'never'}]) {
  assert.throws(() => mergePlanbarSchedulingProgress(null, {status: 'reserved', reservation: {...reservation, ...invalid}}));
}
const reserved = mergePlanbarSchedulingProgress(null, {status: 'reserved', reservation});
assert.match(planbarSchedulingSummary(reserved), /Slot in Planbar gesichert – Angaben noch offen/);
const pending = mergePlanbarSchedulingProgress(reserved, {status:'details_pending', missingDetails:['TMB-Maße nicht lesbar']});
assert.equal(pending.reservation.appointmentId, reservation.appointmentId);
assert.throws(() => mergePlanbarSchedulingProgress(pending, {status:'reserved', reservation:{...reservation, appointmentId:'other'}}), /nicht ersetzt/);
assert.throws(() => mergePlanbarSchedulingProgress(pending, {status:'completed', completionVerified:true}), /Offene/);
assert.throws(() => mergePlanbarSchedulingProgress(pending, {status:'completed', missingDetails:[], remainingActions:[]}), /Offene/);
const completed = mergePlanbarSchedulingProgress(pending, {status:'completed', missingDetails:[], remainingActions:[], completionVerified:true});
assert.match(planbarSchedulingSummary(completed), /vollständig geprüft/);
assert.throws(() => mergePlanbarSchedulingProgress(completed, {status:'details_pending'}), /zurückgesetzt/);

const jobId = '00000000-0000-4000-8000-000000000001';
const directory = path.join(process.env.IVA_CODEX_TASK_ROOT, jobId);
await mkdir(directory, { recursive:true });
const request = { jobId, title:'Fixture reservation', mode:'project-workflow', planbar:input, prompt:'Fixture', createdAt:new Date().toISOString() };
await writeFile(path.join(directory, 'request.json'), JSON.stringify(request));
await writeFile(path.join(directory, 'state.json'), JSON.stringify({jobId, status:'running'}));
const reports = [];
const report = async (...args) => reports.push(args);
await assert.rejects(tasks.recordPlanbarTaskProgress(jobId, {status:'reserved', reservation:{...reservation, isoYear:2026, week:40, ...isoWeekRange(2026,40)}}, {report}), /beauftragten/);
await tasks.recordPlanbarTaskProgress(jobId, {status:'reserved', reservation}, {report});
assert.equal(reports.length, 1);
const afterReserve = await tasks.getCodexTaskStatus(jobId);
assert.equal(afterReserve.status, 'running');
assert.equal(afterReserve.planbarProgress.reservation.appointmentId, 'test-appointment');
await tasks.recordPlanbarTaskProgress(jobId, {status:'details_pending', missingDetails:['Angebot nicht lesbar']}, {report});
const duplicate = await tasks.startPlanbarCustomerSchedulingTask(input);
assert.equal(duplicate.duplicate, true);
assert.equal(duplicate.startedLocally, false, 'Kein zweiter Prozess oder Geschäftsvorgang beim Retry');
assert.equal(duplicate.jobId, jobId);
const prompt = tasks.buildCodexPrompt(request);
assert.match(prompt, /planbar-progress/);
assert.match(prompt, /VOR dem Lesen von Angeboten/);
assert.match(prompt, /completionVerified/);

const externalKey = `codex-task:${jobId}`;
const key = planbarSchedulingKey(input);
assert.equal(key, planbarSchedulingKey({...input, customerName:' fixture  KUNDE '}));
assert.notEqual(key, planbarSchedulingKey({...input, partnerId:'enter'}));
const reported = await operations.upsertExternalAgentRun({externalKey, jobId, schedulingKey:key, status:'running', planbarProgress:reserved});
assert.equal(reported.planbarProgress.reservation.appointmentId, reservation.appointmentId);
const failedFollowup = await operations.upsertExternalAgentRun({externalKey, jobId, status:'failed', error:'Ergänzung fehlgeschlagen'});
assert.match(failedFollowup.resultPreview, /Slot in Planbar gesichert/);
assert.equal(failedFollowup.planbarProgress.status, 'reserved');
const falseComplete = await operations.upsertExternalAgentRun({externalKey, jobId, status:'completed'});
assert.equal(falseComplete.status, 'incomplete', 'Prozessabschluss allein darf nicht vollständigen Erfolg vortäuschen');
await projects.addCustomerSchedulingRequest('heat-hero', input);
const project = await projects.getProject('heat-hero');
assert.equal(project.customerSchedulingRequests[0].status, 'reserved');
assert.match(project.customerSchedulingRequests[0].schedulingSummary, /Angaben noch offen/);
const skill = planbarSkill({deviceCommandStatus:async()=>({status:'completed', result:{jobId}}),listAgentRuns:operations.listAgentRuns});
const skillResult = await skill.checkPlanbarSchedulingDispatch.execute({commandId:jobId});
assert.equal(skillResult.slotReserved, true);
assert.equal(skillResult.taskStatus, 'incomplete');
const noProofSkill = planbarSkill({deviceCommandStatus:async()=>({status:'completed', result:{jobId:'other'}}),listAgentRuns:operations.listAgentRuns});
assert.equal((await noProofSkill.checkPlanbarSchedulingDispatch.execute({commandId:jobId})).slotReserved, false);
await tasks.recordPlanbarTaskProgress(jobId, {status:'completed', missingDetails:[], remainingActions:[], completionVerified:true}, {report});
assert.equal(JSON.parse(await readFile(path.join(directory, 'planbar-progress.json'), 'utf8')).status, 'completed');
await operations.upsertExternalAgentRun({externalKey, jobId, status:'completed', planbarProgress:completed});
assert.equal((await projects.getProject('heat-hero')).customerSchedulingRequests[0].status, 'completed');
console.log('PASS Planbar Slot zuerst: Mindestdaten, Beleggates, offene Ergänzungen, persistenter Reservierungsnachweis, Retry ohne Doppelstart, Projekt-/Chatstatus und Folgefehler. Keine Geschäftsschreibvorgänge.');

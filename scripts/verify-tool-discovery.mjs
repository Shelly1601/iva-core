import assert from 'node:assert/strict';
import {tool} from 'ai';
import {z} from 'zod';
import {compactIvaTools,prepareIvaTool} from '../core/tool-discovery.js';
let calls=0;
const original=tool({description:'Prüft einen erlaubten Beleg.',parameters:z.object({confirmed:z.literal(true),month:z.string().optional(),nested:z.object({note:z.string().optional()}).optional()}),execute:async v=>{calls++;return v}});
const prepared=prepareIvaTool(original);
assert.deepEqual(await prepared.execute({confirmed:true,month:null,nested:{note:null}}),{confirmed:true,nested:{}});
await assert.rejects(()=>prepared.execute({confirmed:null}));
await assert.rejects(()=>prepared.execute({confirmed:false}));
assert.equal(calls,1);
const compact=compactIvaTools({readReceipt:original});
assert.deepEqual((await compact.findIvaTools.execute({query:'readReceipt'})).map(x=>x.name),['readReceipt']);
assert.deepEqual(await compact.executeIvaTool.execute({name:'readReceipt',arguments:{confirmed:true,month:null}}),{confirmed:true});
await assert.rejects(()=>compact.executeIvaTool.execute({name:'constructor',arguments:{}}));
await assert.rejects(()=>compact.executeIvaTool.execute({name:'notAllowed',arguments:{}}));
await assert.rejects(()=>compact.executeIvaTool.execute({name:'readReceipt',arguments:{confirmed:false}}));
assert.equal(calls,2);
const nullable=prepareIvaTool(tool({parameters:z.object({value:z.string().nullable().optional()}),execute:async v=>v}));
assert.deepEqual(await nullable.execute({value:null}),{value:null},'Explicit nullable values must survive normalization.');
assert.equal(compact.readReceipt,undefined);
console.log('Compact tool discovery preserves role scope, required confirmations and original argument validation.');

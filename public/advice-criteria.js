const sameLabel = value => String(value).trim().replace(/\s+/g, ' ').toLocaleLowerCase('de-DE');
export function appendInsuranceCriteria(existing, { category, profileId, criterionIds }) {
  if (!Array.isArray(existing) || !Array.isArray(criterionIds) || !criterionIds.length || new Set(criterionIds).size !== criterionIds.length) throw new Error('Bitte relevante Prüffragen eindeutig auswählen.');
  const preset = INSURANCE_CRITERIA_PROFILES.find(item => item.id === profileId && item.category === category);
  if (!preset || criterionIds.some(id => !preset.criteria.some(item => item.id === id))) throw new Error('Die Prüffragen gehören nicht zu diesem Spartenprofil.');
  const ids = new Set(existing.map(item => item.id)), labels = new Set(existing.map(item => sameLabel(item.label)));
  const added = preset.criteria.filter(item => criterionIds.includes(item.id) && !ids.has(item.id) && !labels.has(sameLabel(item.label)));
  if (existing.length + added.length > 30) throw new Error(`Maximal 30 Kriterien pro Vergleich. Bitte höchstens ${Math.max(0, 30 - existing.length)} weitere Prüffragen wählen.`);
  return [...existing.map(item => structuredClone(item)), ...added.map(item => ({ ...item }))];
}
